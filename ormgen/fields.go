// header starts every file ormgen writes.
const header = "// Code generated by ormgen. DO NOT EDIT."

// FieldsName is the file holding the typed fields of the models declared
// in file: post.go's in post_gen.go, post_test.go's in post_gen_test.go,
// and a .vuka file's (post.vuka, transpiled to post_vuka.go) in post_gen.go.
func FieldsName(file string) string {
	base := strings.TrimSuffix(filepath.Base(file), ".go")
	base, test := strings.CutSuffix(base, "_test")
	base = strings.TrimSuffix(strings.TrimSuffix(base, ".vuka"), "_vuka")
	if test {
		return base + "_gen_test.go"
	}
	return base + "_gen.go"
}

// typedField is a column of a model's typed fields.
type typedField struct {
	goName, path string
	typ          types.Type // the value lookups compare it with
	text         bool       // a string kind: a TextField
	number       bool       // an integer or float kind: a NumberField
}

// typedRel is a relation of a model's typed fields.
type typedRel struct {
	goName, path string
	target       *types.Named
	declaration  string
}

// typedFields is st's columns and relations as its typed fields name them:
// the fields of the structs it embeds flattened as Go promotes them, an
// outer field shadowing an embedded one.
func (g *gen) typedFields(st *types.Struct) ([]typedField, []typedRel) {
	var cols []typedField
	var rels []typedRel
	depth := map[string]int{}
	shadowed := func(name string, d int) bool {
		if old, ok := depth[name]; ok && old <= d {
			return true
		}
		depth[name] = d
		cols = deleteNamed(cols, name)
		for i, r := range rels {
			if r.goName == name {
				rels = append(rels[:i], rels[i+1:]...)
				break
			}
		}
		return false
	}
	var walk func(st *types.Struct, prefix string, d int)
	walk = func(st *types.Struct, prefix string, d int) {
		for i := range st.NumFields() {
			f := st.Field(i)
			tag := tags.Parse(f.Name(), reflect.StructTag(st.Tag(i)), isTime(f.Type()))
			if tag.Skip || tag.Computed {
				continue
			}
			t := f.Type()
			if p, ok := t.(*types.Pointer); ok && !isScanner(t) {
				t = p.Elem()
			}
			if sub, ok := t.Underlying().(*types.Struct); ok && !isValue(t) && (f.Anonymous() || tag.Embedded) {
				p := prefix
				if tag.Embedded && !f.Anonymous() {
					p += tag.Prefix
				}
				walk(sub, p, d+1)
				continue
			}
			if target, ok := g.relTarget(f.Type()); ok {
				if f.Exported() && !shadowed(f.Name(), d) {
					rels = append(rels, typedRel{f.Name(), prefix + tags.Snake(f.Name()), target, ""})
				}
				continue
			}
			if inner, ok := optionElem(t); ok {
				t = inner
			}
			if !f.Exported() || !isValue(t) || shadowed(f.Name(), d) {
				continue
			}
			col := tag.Column
			if col == "" {
				col = tags.Snake(f.Name())
			}
			b, ok := t.Underlying().(*types.Basic)
			cols = append(cols, typedField{f.Name(), prefix + col, t, ok && b.Info()&types.IsString != 0,
				ok && b.Info()&(types.IsInteger|types.IsFloat) != 0})
		}
	}
	walk(st, "", 0)
	return cols, rels
}

// reverseFields finds the explicitly named inverse relations reaching n.
func (g *gen) reverseFields(n *types.Named) []typedRel {
	var out []typedRel
	for owner := range g.models {
		st, ok := owner.Underlying().(*types.Struct)
		if !ok {
			continue
		}
		for i := range st.NumFields() {
			f := st.Field(i)
			tag := tags.Parse(f.Name(), reflect.StructTag(st.Tag(i)), isTime(f.Type()))
			target, ok := g.relTarget(f.Type())
			if tag.Related == "" {
				tag.Related = g.related[typeKey(owner)+"."+f.Name()]
			}
			if !ok || tag.Related == "" || tag.Related == "+" || typeKey(target) != typeKey(n) {
				continue
			}
			name := tag.Related
			name = strings.ToUpper(name[:1]) + name[1:]
			out = append(out, typedRel{name, tag.Related, owner, owner.Obj().Name() + "." + f.Name()})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].goName < out[j].goName })
	return out
}

func deleteNamed(cols []typedField, name string) []typedField {
	for i, c := range cols {
		if c.goName == name {
			return append(cols[:i], cols[i+1:]...)
		}
	}
	return cols
}

// relTarget is the model a relation field of type t leads to: an orm.FK or
// orm.M2M of it, the model, a pointer to it, or a slice of either. Only
// models with typed fields of their own count.
func (g *gen) relTarget(t types.Type) (*types.Named, bool) {
	if s, ok := t.(*types.Slice); ok {
		t = s.Elem()
	}
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	n, ok := t.(*types.Named)
	if !ok {
		return nil, false
	}
	if o := n.Origin().Obj(); o.Pkg() != nil && o.Pkg().Path() == ormPath && (o.Name() == "FK" || o.Name() == "M2M") && n.TypeArgs().Len() == 1 {
		n, ok = n.TypeArgs().At(0).(*types.Named)
		if !ok {
			return nil, false
		}
	}
	return n, g.typed[typeKey(n)]
}

// typeKey names a model across the loads of its package (with and without
// its tests).
func typeKey(n *types.Named) string { return n.Obj().Pkg().Path() + "." + n.Obj().Name() }

// optionElem is T of a vuka.Option[T].
func optionElem(t types.Type) (types.Type, bool) {
	n, ok := t.(*types.Named)
	if !ok || n.TypeArgs().Len() != 1 {
		return nil, false
	}
	if o := n.Origin().Obj(); o.Pkg() != nil && o.Pkg().Path() == "github.com/vuka-lang/vuka/v2" && o.Name() == "Option" {
		return n.TypeArgs().At(0), true
	}
	return nil, false
}

// fieldsFile is the typed fields of the models declared in one file:
// for each, <Model>Fields, the model's fields and its relations' as
// fields, and <Model>Path, its fields under a relation path, whose own
// relations are methods (a type can't hold itself).
func (g *gen) fieldsFile(pkg *types.Package, models []*types.Named) ([]byte, error) {
	sort.Slice(models, func(i, j int) bool { return models[i].Obj().Pos() < models[j].Obj().Pos() })
	o := "orm."
	imports := map[string]string{ormPath: "orm"}
	if pkg.Path() == ormPath {
		o, imports = "", map[string]string{}
	}
	qual := qualifier(pkg, imports)
	var body bytes.Buffer
	for _, n := range models {
		st := n.Underlying().(*types.Struct)
		cols, rels := g.typedFields(st)
		for _, r := range g.reverseFields(n) {
			for _, c := range cols {
				if c.goName == r.goName {
					return nil, fmt.Errorf("ormgen: Related %s.%s clashes with field %s.%s; choose a different Related name", n.Obj().Name(), r.goName, n.Obj().Name(), c.goName)
				}
			}
			exists := false
			for _, old := range rels {
				if old.goName == r.goName {
					if old.declaration == "" && typeKey(old.target) == typeKey(r.target) {
						exists = true
						break
					}
					return nil, fmt.Errorf("ormgen: Related %s.%s from %s clashes with %s; choose a different Related name", n.Obj().Name(), r.goName, r.declaration, old.declaration)
				}
			}
			if exists {
				continue
			}
			rels = append(rels, r)
		}
		if len(cols)+len(rels) == 0 {
			continue
		}
		imports["strings"] = "strings"
		name := n.Obj().Name()
		path, fields := name+"Fields", name+"Columns"
		ref := func(t *types.Named, suffix string) string {
			if q := qual(t.Obj().Pkg()); q != "" {
				return q + "." + t.Obj().Name() + suffix
			}
			return t.Obj().Name() + suffix
		}

		fmt.Fprintf(&body, "// %sPath is the compatibility name for %s.\ntype %sPath = %s\n\n", name, path, name, path)
		fmt.Fprintf(&body, "func %sPathAt(prefix string) %s { return %sAt(prefix) }\n\n", name, path, path)
		fmt.Fprintf(&body, "// %s is %s's fields as typed lookups.\n", fields, name)
		if len(rels) == 0 {
			fmt.Fprintf(&body, "var %s = %sAt(\"\")\n\n", fields, path)
		} else {
			fmt.Fprintf(&body, "var %s = struct {\n\t%s\n", fields, path)
			for _, r := range rels {
				fmt.Fprintf(&body, "\t%s %s\n", r.goName, ref(r.target, "Path"))
			}
			fmt.Fprintf(&body, "}{\n\t%s: %sAt(\"\"),\n", path, path)
			for _, r := range rels {
				fmt.Fprintf(&body, "\t%s: %s(%q),\n", r.goName, ref(r.target, "PathAt"), r.path+"__")
			}
			fmt.Fprintf(&body, "}\n\n")
		}

		fmt.Fprintf(&body, "// %s is %s's fields reached through a relation to %s.\n", path, name, name)
		fmt.Fprintf(&body, "type %s struct {\n\t%sRelationPath\n\tprefix string\n", path, o)
		for _, c := range cols {
			fmt.Fprintf(&body, "\t%s %s\n", c.goName, fieldType(o, c, qual))
		}
		fmt.Fprintf(&body, "}\n\n")
		fmt.Fprintf(&body, "// %sAt is %s's fields under prefix, a relation path ending in \"__\".\n", path, name)
		fmt.Fprintf(&body, "func %sAt(prefix string) %s {\n\treturn %s{\n\t\tRelationPath: %sRelationAt(strings.TrimSuffix(prefix, \"__\")),\n\t\tprefix: prefix,\n", path, path, path, o)
		for _, c := range cols {
			ctor := strings.Replace(fieldType(o, c, qual), "Field", "FieldAt", 1)
			fmt.Fprintf(&body, "\t\t%s: %s(prefix + %q),\n", c.goName, ctor, c.path)
		}
		fmt.Fprintf(&body, "\t}\n}\n\n")
		fmt.Fprintf(&body, "// String is the relation path, for Load and PrefetchRelated.\n")
		fmt.Fprintf(&body, "func (p %s) String() string { return strings.TrimSuffix(p.prefix, \"__\") }\n\n", path)
		for _, r := range rels {
			fmt.Fprintf(&body, "// %s is the fields of %s's %s.\nfunc (p %s) %s() %s { return %s(p.prefix + %q) }\n\n",
				r.goName, name, r.goName, path, r.goName, ref(r.target, "Path"), ref(r.target, "PathAt"), r.path+"__")
		}
	}
	if body.Len() == 0 {
		return nil, nil
	}
	return source(pkg, imports, body.Bytes())
}

func fieldType(o string, c typedField, qual types.Qualifier) string {
	if isTime(c.typ) {
		return o + "TimeField"
	}
	kind := "Field"
	switch {
	case c.text:
		kind = "TextField"
	case c.number:
		kind = "NumberField"
	}
	return o + kind + "[" + types.TypeString(c.typ, qual) + "]"
}

// qualifier names pkg's imports as the generated file imports them, adding
// each package it is asked about to imports.
func qualifier(pkg *types.Package, imports map[string]string) types.Qualifier {
	return func(p *types.Package) string {
		if p == pkg {
			return ""
		}
		if name, ok := imports[p.Path()]; ok {
			return name
		}
		name := p.Name()
		for taken := true; taken; {
			taken = false
			for _, n := range imports {
				if n == name {
					name += "_"
					taken = true
				}
			}
		}
		imports[p.Path()] = name
		return name
	}
}

// source is a generated file of pkg: its header, imports and body, gofmt'd.
func source(pkg *types.Package, imports map[string]string, body []byte) ([]byte, error) {
	var src bytes.Buffer
	fmt.Fprintf(&src, "%s\n\npackage %s\n\n", header, pkg.Name())
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	sort.SliceStable(paths, func(i, j int) bool { return std(paths[i]) && !std(paths[j]) })
	if len(paths) > 0 {
		src.WriteString("import (\n")
		for i, p := range paths {
			if i > 0 && std(paths[i-1]) && !std(p) {
				src.WriteString("\n")
			}
			if imports[p] == pathTail(p) {
				fmt.Fprintf(&src, "\t%q\n", p)
			} else {
				fmt.Fprintf(&src, "\t%s %q\n", imports[p], p)
			}
		}
		src.WriteString(")\n\n")
	}
	src.Write(body)
	out, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("ormgen: %s: %w\n%s", pkg.Path(), err, src.String())
	}
	return out, nil
}

// std is whether an import path is the standard library's.
func std(path string) bool { return !strings.Contains(strings.Split(path, "/")[0], ".") }

// generated is whether the file at path is one ormgen wrote (or none is
// there).
func generated(path string) bool {
	b, err := os.ReadFile(path)
	return err != nil || bytes.HasPrefix(b, []byte(header))
}
