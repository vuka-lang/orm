func (o RunSQL) source() string {
	s := "m.RunSQL{SQL: " + str(o.SQL)
	if o.ReverseSQL == Noop {
		s += ", ReverseSQL: m.Noop"
	} else if o.ReverseSQL != "" {
		s += ", ReverseSQL: " + str(o.ReverseSQL)
	}
	if o.Dialect != "" {
		s += ", Dialect: " + str(o.Dialect)
	}
	return s + "}"
}

func (o CreateFunction) source() string {
	s := "m.CreateFunction{Name: " + str(o.Name) + ", Params: " + dialects(o.Params) + ", Returns: " + dialects(o.Returns) + ", Body: " + dialects(o.Body)
	if o.Language != "" {
		s += ", Language: " + str(o.Language)
	}
	if o.Volatile {
		s += ", Volatile: true"
	}
	return s + "}"
}

// source is a RunGo to fill in: its functions can't be written back.
func (o RunGo) source() string {
	return `m.RunGo{
Forward: func(ctx context.Context, tx m.Tx) error {
return nil
},
Backward: func(ctx context.Context, tx m.Tx) error {
return nil
},
}`
}
